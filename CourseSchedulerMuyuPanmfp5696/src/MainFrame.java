    private void scheduleClassSubmitBottumActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_scheduleClassSubmitBottumActionPerformed
        String classes = scheduleClassComboBox.getSelectedItem().toString();
        String students = scheduleClassSelectStudentComboBox.getSelectedItem().toString();
        int seats = ClassQueries.getClassSeats(currentSemester, classes);
        int seats_taken = ScheduleQueries.getScheduledStudentCount(currentSemester, classes);
        String status = "";
        System.out.print(seats);
        System.out.print(seats_taken);
        if (seats > seats_taken) {
            status = "S";
            scheduleClassLabel.setText("message displayed that the class was scheduled.");
        } else {
            status = "W";
            scheduleClassLabel.setText("message displayed that the class was waitlisted.");
        }
        java.sql.Timestamp timestamp = new java.sql.Timestamp(Calendar.getInstance().getTime().getTime());
        ScheduleEntry entry = new ScheduleEntry(currentSemester, classes, students, status, timestamp);
        ScheduleQueries.addScheduleEntry(entry);
    


    }//GEN-LAST:event_scheduleClassSubmitBottumActionPerformed

