    public void rebuildSemesterComboBoxes() {
        ArrayList<String> semesters = SemesterQueries.getSemesterList();
        currentSemesterComboBox.setModel(new javax.swing.DefaultComboBoxModel(semesters.toArray()));
        if (semesters.size() > 0) {
            currentSemesterLabel.setText(semesters.get(0));
            currentSemester = semesters.get(0);
        } else {
            currentSemesterLabel.setText("None, add a semester.");
            currentSemester = "None";
        }
    }

    public void rebuildCourseComboBoxes() {
        ArrayList<String> courses = CourseQueries.getAllCourseCodes();
        addClassCourseCodeComboBox.setModel(new javax.swing.DefaultComboBoxModel(courses.toArray()));

    }

    public void rebuildStudentsComboBoxes() {
        ArrayList<StudentEntry> students = StudentQueries.getAllStudents();
        ArrayList<String> names = new ArrayList();
        for (StudentEntry student : students) {
            names.add(student.getLastName() + ", " + student.getFirstName());
        }
        displayStudentScheduleComboBox.setModel(new javax.swing.DefaultComboBoxModel(names.toArray()));
        scheduleClassSelectStudentComboBox.setModel(new javax.swing.DefaultComboBoxModel(names.toArray()));

    }

    public void rebuildClassesComboBoxes() {
        ArrayList<String> classes = ClassQueries.getAllCourseCodes(currentSemester);
        scheduleClassComboBox.setModel(new javax.swing.DefaultComboBoxModel(classes.toArray()));

    }

